#!/usr/bin/env python3
# BlakeStone32X: writes port/bs32x_colormap_rot.inc, the game's colormap with
# every 256-byte row rotated by 128 (for the SH2 loops that index the shade
# table with a sign-extended byte).  Run from the repo root.
import re
src = open('bstone/colormap.cpp').read()
body = src[src.index('colormap[16896] = {') + 19:]
vals = [int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', body)]
assert len(vals) == 16896, len(vals)
rot = []
for r in range(66):
    row = vals[r * 256:(r + 1) * 256]
    rot += [row[(j + 128) & 255] for j in range(256)]
out = ['/* generated by tools/gen_colormap_rot.py from bstone/colormap.cpp: rows rotated by 128 */']
for i in range(0, len(rot), 16):
    out.append(', '.join('0x%02X' % v for v in rot[i:i + 16]) + ',')
open('port/bs32x_colormap_rot.inc', 'w').write('\n'.join(out) + '\n')
