// Generates port/bs32x_trig.inc: Blake Stone's finetangent and sintable,
// computed exactly as BuildTables() does, so the 32X keeps them in ROM.
#include <cmath>
#include <cstdio>
#include <cstdint>
#define PI (3.141592657)
#define GLOBAL1 (1L << 16)
#define TILEGLOBAL (GLOBAL1)
#define ANGLES (360)
#define ANGLEQUAD (ANGLES / 4)
#define FINEANGLES (3600)
int main()
{
    static int32_t finetangent[FINEANGLES / 4];
    static int32_t sintable[ANGLES + (ANGLES / 4) + 1];
    const float radtoint = static_cast<float>(FINEANGLES / 2 / PI);
    for (int i = 0; i < FINEANGLES / 8; i++) {
        double tang = tan((i + 0.5) / radtoint);
        finetangent[i] = static_cast<int32_t>(tang * TILEGLOBAL);
        finetangent[FINEANGLES / 4 - 1 - i] = static_cast<int32_t>(1 / tang * TILEGLOBAL);
    }
    float angle = 0.0F;
    float anglestep = static_cast<float>(PI / 2 / ANGLEQUAD);
    for (int i = 0; i <= ANGLEQUAD; i++) {
        int32_t value = static_cast<int32_t>(GLOBAL1 * sin(static_cast<double>(angle)));
        sintable[i] = sintable[i + ANGLES] = sintable[ANGLES / 2 - i] = value;
        sintable[ANGLES - i] = sintable[ANGLES / 2 + i] = value | static_cast<int32_t>(0x80000000u);
        angle += anglestep;
    }
    std::printf("// generated by tools/gen_trig.cpp (same math as BuildTables)\n");
    std::printf("const int finetangent[FINEANGLES / 4] = {\n");
    for (int i = 0; i < FINEANGLES / 4; i++) std::printf("%d,%s", finetangent[i], (i % 8 == 7) ? "\n" : " ");
    std::printf("};\nconst int sintable[ANGLES + (ANGLES / 4) + 1] = {\n");
    for (int i = 0; i < ANGLES + ANGLES / 4 + 1; i++) std::printf("%d,%s", sintable[i], (i % 8 == 7) ? "\n" : " ");
    std::printf("};\n");
}
