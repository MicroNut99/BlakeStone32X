#!/usr/bin/env python3
# BlakeStone32X: writes port/bs32x_ray.inc, a copy of the game's ray caster
# (AsmRefresh, CalcHeight and the Hit* functions) that bs32x_render.cpp
# includes once per CPU, each copy with its own state, so both SH2s can cast
# rays at the same time (one the even columns, the other the odd ones).
# The copy is taken from the BStone sources so it stays the same code.
# Run from the repo root.
import re

def func(src, signature):
    """the text of the function that starts with 'signature' (up to its closing brace)"""
    i = src.index(signature)
    j = src.index('{', i)
    depth = 0
    k = j
    while True:
        c = src[k]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return src[i:k + 1]
        k += 1

dr2 = open('bstone/d3_dr2.cpp').read()
draw = open('bstone/3d_draw.cpp').read()

out = ['// generated by tools/gen_ray_inc.py from bstone/d3_dr2.cpp and bstone/3d_draw.cpp',
       '// (included by port/bs32x_render.cpp inside one namespace per CPU)', '',
       '#ifndef MASKABLE_DOORS',
       '#define MASKABLE_DOORS (0)',
       '#define DOORWALL (PMSpriteStart - (NUMDOORTYPES))',
       '#endif',
       'static const int DEG90 = 900;',
       'static const int DEG180 = 1800;',
       'static const int DEG270 = 2700;',
       'static const int DEG360 = 3600;', '']

out.append(func(dr2, 'static int partial_by_step('))
out.append('')

calc = func(draw, 'int CalcHeight()')
# the 32X divide
calc = calc.replace('''#ifdef BS32X
    int result = bs32x_div(heightnumerator, nx / 256);
#else
    int result = heightnumerator / (nx / 256);
#endif''', '    int result = bs32x_div(heightnumerator, nx / 256);')
out.append(calc)
out.append('')

for name in ['void HitVertWall()', 'void HitHorizWall()', 'void HitHorizDoor()',
             'void HitVertDoor()', 'void HitHorizPWall()', 'void HitVertPWall()']:
    out.append(func(draw, name))
    out.append('')

cast = func(dr2, 'void AsmRefresh()')
cast = cast.replace('void AsmRefresh()', 'void cast_rays(int first_x)', 1)
assert cast.count('    pixx = 0;\n') == 1
cast = cast.replace('    pixx = 0;\n', '    pixx = first_x;\n', 1)
assert cast.count('nextpix:\n    ++pixx;') == 1
cast = cast.replace('nextpix:\n    ++pixx;', 'nextpix:\n    pixx += 2;', 1)
out.append(cast)
out.append('')

open('port/bs32x_ray.inc', 'w').write('\n'.join(out))
print('port/bs32x_ray.inc written')
